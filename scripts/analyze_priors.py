"""The three-way control on the guidance channel.

The ablation localises Approx-LG's advantage in one operator, the ranked list
of compressor styles per column offset that biases every mutation.  That is a
statement about the *channel*, not about the model, and a reviewer is right to
ask which of the two the paper is really about.  These four arms are the same
NSGA-II -- same sampler, crossover, mutation rates, epsilon and geometric rank
draw -- and differ only in where the ranked list comes from: nowhere, a fixed
designer prior, online credit assignment, or the model.  Approx-LG itself is
included for scale, since it adds three further operators on top of the same
channel.

Runs pair by seed, because the seed also seeds the initial population and the
sampler is shared, so the paired test is the one with power here.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from collections import defaultdict

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analyze_search import mannwhitney, wilcoxon_paired      # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(ROOT, "results")
TABS = os.path.join(ROOT, "paper", "tabs")

ARMS = [
    ("nsga2", "uniform (NSGA-II)"),
    ("nsga2_expert", "fixed designer prior"),
    ("nsga2_adaptive", "adaptive prior (UCB)"),
    ("nsga2_llmprior", "elicited prior (LLM)"),
    ("approxlg", "Approx-LG (all four operators)"),
]


def load(tags):
    by = defaultdict(list)
    for tag in tags:
        p = os.path.join(RESULTS, f"search_{tag}.jsonl")
        if not os.path.exists(p):
            continue
        for line in open(p):
            if line.strip():
                d = json.loads(line)
                by[d["algo"]].append(d)
    return by


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", nargs="+", default=["n8", "n8L", "n8p"])
    ap.add_argument("--suffix", default="n8")
    args = ap.parse_args()
    os.makedirs(TABS, exist_ok=True)
    by = load(args.tag)
    hv = {a: {r["seed"]: r["hv"] for r in by[a]} for a, _ in ARMS if a in by}
    if "nsga2" not in hv:
        raise SystemExit("no NSGA-II runs")
    base = hv["nsga2"]

    rows, out = [], {}
    print(f"{'arm':34s} {'runs':>4s} {'HV':>8s} {'delta':>7s} "
          f"{'wins':>7s} {'p':>7s}")
    for algo, label in ARMS:
        if algo not in hv:
            continue
        v = np.array(list(hv[algo].values()))
        common = sorted(set(hv[algo]) & set(base))
        if algo == "nsga2" or len(common) < 6:
            d = p = float("nan")
            wins = n = 0
        else:
            A = np.array([hv[algo][s] for s in common])
            N = np.array([base[s] for s in common])
            d = 100.0 * float(np.mean((A - N) / N))
            p, wins, n = wilcoxon_paired(A, N)
        rows.append((label, len(v), v.mean(), v.std(), d, wins, n, p))
        out[algo] = {"runs": len(v), "hv": float(v.mean()),
                     "std": float(v.std()), "gain": d, "wins": wins,
                     "n": n, "p": p}
        print(f"{label:34s} {len(v):4d} {v.mean():8.4f} "
              + (f"{d:+6.1f}%" if d == d else "     --")
              + (f" {wins:3d}/{n:<3d}" if n else "     --")
              + (f" {p:7.3f}" if p == p else "     --"))

    # the sharpest single question: elicited prior against the two controls
    for other in ("nsga2_expert", "nsga2_adaptive"):
        if other in hv and "nsga2_llmprior" in hv:
            common = sorted(set(hv[other]) & set(hv["nsga2_llmprior"]))
            if len(common) >= 6:
                A = np.array([hv["nsga2_llmprior"][s] for s in common])
                B = np.array([hv[other][s] for s in common])
                p, w, n = wilcoxon_paired(A, B)
                pu, a12 = mannwhitney(A, B)
                out[f"llmprior_vs_{other}"] = {
                    "gain": 100.0 * float(np.mean((A - B) / B)),
                    "wins": w, "n": n, "p": p, "p_unpaired": pu, "a12": a12}
                print(f"\nelicited prior vs {other}: "
                      f"{100*np.mean((A-B)/B):+.1f}%, {w}/{n} pairs, "
                      f"paired p={p:.3f}, unpaired p={pu:.3f}, A12={a12:.2f}")

    with open(os.path.join(TABS, f"prior_{args.suffix}.tex"), "w") as fh:
        fh.write("% generated by scripts/analyze_priors.py\n")
        for (label, n_, m, s, d, w, n, p) in rows:
            dd = "--" if d != d else f"{d:+.1f}\\%"
            ww = "--" if not n else f"{w}/{n}"
            pp = ("--" if p != p else
                  ("$<$0.01" if p < 0.005 else f"{p:.2f}"))
            fh.write(f"{label} & {n_} & {m:.4f} $\\pm$ {s:.4f} & {dd} & "
                     f"{ww} & {pp} \\\\\n")
    with open(os.path.join(TABS, f"prior_{args.suffix}.json"), "w") as fh:
        json.dump(out, fh, indent=1)
    print("\nwrote", os.path.join(TABS, f"prior_{args.suffix}.tex"))


if __name__ == "__main__":
    main()
