"""Parameterised approximate-multiplier architecture template.

A design point ("genome") is decoded into a *structural* netlist that is used
for two purposes at once:

  * bit-accurate functional simulation (:mod:`approxlg.simulate`), and
  * synthesisable Verilog emission (:meth:`Netlist.to_verilog`).

Because both views are generated from the same object, the error metrics and
the PPA metrics are guaranteed to describe the same circuit.

Architecture template
---------------------
    1. Partial-product generation (AND array).  The ``T`` least-significant
       columns are *truncated*: their partial products are not generated.
       An optional constant compensates the mean truncation error.
    2. Dadda reduction.  Each (stage, column) slot carries a gene selecting
       the compressor style used in that slot; slots in columns >= T+A are
       forced to the exact full/half adder.
    3. Final carry-propagate addition, whose ``cpa_k`` least-significant bits
       may be replaced by an OR-based (LOA-style) approximate adder.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Sequence, Tuple

import numpy as np

from .cells import CELL_BY_NAME, SLOT_MODES, SLOT_MODE_BY_NAME, N_SLOT_MODES, Cell


# --------------------------------------------------------------------------
# Netlist
# --------------------------------------------------------------------------
@dataclass
class Stmt:
    kind: str                 # 'and' | 'cell' | 'or'
    outs: List[str]
    ins: List[str]
    cell: Cell | None = None


@dataclass
class Netlist:
    n: int
    stmts: List[Stmt] = field(default_factory=list)
    row_a: Dict[int, str] = field(default_factory=dict)   # column -> wire
    row_b: Dict[int, str] = field(default_factory=dict)
    trunc: int = 0
    cpa_k: int = 0
    const_add: int = 0
    n_cells: int = 0
    n_approx_cells: int = 0
    signed: bool = False

    # ---------------- Verilog ----------------
    def to_verilog(self, module: str = "mul") -> str:
        n, m = self.n, 2 * self.n
        wires = []
        lines = []
        for st in self.stmts:
            if st.kind == "and":
                wires.append(st.outs[0])
                lines.append(f"  assign {st.outs[0]} = {st.ins[0]} & {st.ins[1]};")
            elif st.kind == "nand":
                wires.append(st.outs[0])
                lines.append(f"  assign {st.outs[0]} = "
                             f"~({st.ins[0]} & {st.ins[1]});")
            elif st.kind == "const":
                wires.append(st.outs[0])
                lines.append(f"  assign {st.outs[0]} = 1'b1;")
            elif st.kind == "or":
                wires.append(st.outs[0])
                lines.append(f"  assign {st.outs[0]} = " + " | ".join(st.ins) + ";")
            else:
                env = {nm: iw for nm, iw in zip("abcd", st.ins)}
                for o, (w, expr) in zip(st.outs, st.cell.outs):
                    wires.append(o)
                    e = _subst(expr, env)
                    lines.append(f"  assign {o} = {e};")

        lo = self.trunc + self.cpa_k          # first bit handled by the exact CPA
        body = []
        body.append(f"module {module}(input [{n-1}:0] a, input [{n-1}:0] b, "
                    f"output [{m-1}:0] p);")
        if wires:
            body.append("  wire " + ", ".join(wires) + ";")
        body.extend(lines)

        # ---- approximate (OR) part of the final adder --------------------
        loa_bits = []
        for j in range(self.trunc, lo):
            terms = [w for w in (self.row_a.get(j), self.row_b.get(j)) if w]
            loa_bits.append("1'b0" if not terms else "(" + " | ".join(terms) + ")")
        # LOA carry-in: generated by the most significant OR-ed column
        cin = "1'b0"
        if self.cpa_k > 0:
            j = lo - 1
            if self.row_a.get(j) and self.row_b.get(j):
                cin = f"({self.row_a[j]} & {self.row_b[j]})"

        # ---- exact part of the final adder -------------------------------
        hi = m - lo
        va = _bus(self.row_a, lo, m, hi)
        vb = _bus(self.row_b, lo, m, hi)
        const_hi = self.const_add >> lo
        body.append(f"  wire [{hi-1}:0] rowa = {va};")
        body.append(f"  wire [{hi-1}:0] rowb = {vb};")
        term = f"rowa + rowb + {{{hi-1}'b0, {cin}}}"
        if const_hi:
            term += f" + {hi}'d{const_hi}"
        body.append(f"  wire [{hi-1}:0] hi_sum = {term};")

        parts = [f"hi_sum"]
        if lo > self.trunc:
            parts.append("{" + ", ".join(reversed(loa_bits)) + "}")
        if self.trunc:
            parts.append(f"{self.trunc}'b0")
        body.append("  assign p = {" + ", ".join(parts) + "};")
        body.append("endmodule")
        return "\n".join(body) + "\n"


def _bus(row: Dict[int, str], lo: int, m: int, width: int) -> str:
    bits = []
    for j in range(lo + width - 1, lo - 1, -1):
        bits.append(row.get(j) or "1'b0")
    return "{" + ", ".join(bits) + "}"


def _subst(expr: str, env: Dict[str, str]) -> str:
    out = []
    for ch in expr:
        out.append(env[ch] if ch in env else ch)
    return "".join(out)


# --------------------------------------------------------------------------
# Genome
# --------------------------------------------------------------------------
def dadda_targets(max_height: int) -> List[int]:
    d = [2]
    while d[-1] < max_height:
        d.append(d[-1] * 3 // 2)
    return list(reversed(d[:-1]))          # e.g. 8 -> [6, 4, 3, 2]


class Space:
    """Bounds and (de)coding of the design space for an N x N multiplier."""

    def __init__(self, n: int = 8, signed: bool = False):
        self.n = n
        self.signed = signed
        self.ncol = 2 * n - 1
        self.targets = dadda_targets(n)
        self.nstage = len(self.targets)
        self.max_t = 2 * n - 3
        # gene layout: [T, A, comp, cpa_k] + nstage*ncol slot genes
        self.n_head = 4
        self.length = self.n_head + self.nstage * self.ncol
        hi = [self.max_t + 1, self.ncol + 1, 4, self.ncol + 1]
        hi += [N_SLOT_MODES] * (self.nstage * self.ncol)
        self.hi = np.array(hi, dtype=np.int32)      # exclusive upper bounds

    # -- canonicalisation: fold inactive genes so that equal circuits hash equal
    def canonical(self, g: np.ndarray) -> np.ndarray:
        g = np.asarray(g, dtype=np.int32).copy()
        g[:self.n_head] = np.clip(g[:self.n_head], 0, self.hi[:self.n_head] - 1)
        t = int(g[0])
        a = int(min(g[1], self.ncol - t))
        g[1] = a
        g[3] = int(min(g[3], a))
        slots = g[self.n_head:].reshape(self.nstage, self.ncol) % N_SLOT_MODES
        for j in range(self.ncol):
            if j < t or j >= t + a:
                slots[:, j] = 0                      # exact / unused
        g[self.n_head:] = slots.reshape(-1)
        if t == 0 and a == 0:
            g[2] = 0
        return g

    def random(self, rng: np.random.Generator, exact_bias: float = 0.55) -> np.ndarray:
        """Sample a design point.

        The truncation width is drawn from a distribution skewed towards small
        values: the error grows as 4^T, so a uniform draw would place almost
        every random design in the useless high-error corner.  The same sampler
        is used to seed every algorithm compared in the paper."""
        g = np.empty(self.length, dtype=np.int32)
        g[0] = int(round((self.max_t) * rng.random() ** 1.7))
        g[1] = rng.integers(0, self.ncol - int(g[0]) + 1)
        g[2] = rng.integers(0, 4)
        g[3] = rng.integers(0, int(g[1]) + 1)
        slots = rng.integers(0, N_SLOT_MODES, size=self.nstage * self.ncol)
        mask = rng.random(slots.shape) < exact_bias
        slots[mask] = 0
        g[self.n_head:] = slots
        return self.canonical(g)

    def key(self, g: np.ndarray) -> bytes:
        return self.canonical(g).astype(np.int8).tobytes()

    def describe(self, g: np.ndarray) -> str:
        g = self.canonical(g)
        t, a, comp, k = (int(x) for x in g[:4])
        slots = g[self.n_head:].reshape(self.nstage, self.ncol)
        rows = []
        for s in range(self.nstage):
            used = {j: SLOT_MODES[slots[s, j]].name for j in range(self.ncol)
                    if slots[s, j] != 0}
            if used:
                rows.append(f"    stage{s}: " + ", ".join(
                    f"c{j}={v}" for j, v in sorted(used.items())))
        head = f"T={t} A={a} comp={comp} cpa_k={k}"
        return head + ("\n" + "\n".join(rows) if rows else "  (all-exact tree)")


# --------------------------------------------------------------------------
# Decoder: genome -> netlist
# --------------------------------------------------------------------------
class Builder:
    def __init__(self, space: Space):
        self.space = space

    def build(self, g: np.ndarray, perm: np.ndarray | None = None) -> Netlist:
        """Decode a genome.

        ``perm`` optionally carries a (nstage x ncol) matrix of input-ordering
        codes used by the reproduction of the greedy input-order adjustment of
        Wen et al.; 0 = natural order, 1 = reversed, 2 = rotate by one.
        """
        sp = self.space
        g = sp.canonical(g)
        n, ncol = sp.n, sp.ncol
        t, a, comp, cpa_k = (int(x) for x in g[:4])
        slots = g[sp.n_head:].reshape(sp.nstage, ncol)

        signed = getattr(sp, "signed", False)
        nl = Netlist(n=n, trunc=t, cpa_k=cpa_k, signed=signed)
        self._uid = 0

        # ---- 1. partial products -------------------------------------
        # Unsigned: a plain AND array.  Signed: the Baugh-Wooley array, in
        # which the partial products of the two sign columns are inverted and
        # two correction ones are injected at columns n and 2n-1.
        cols: List[List[str]] = [[] for _ in range(ncol)]
        n_pp_trunc = 0
        for i in range(n):                      # b index
            for j in range(n):                  # a index
                c = i + j
                if c < t:
                    n_pp_trunc += 1
                    continue
                neg = signed and ((i == n - 1) != (j == n - 1))
                w = self._new("pp")
                nl.stmts.append(Stmt("nand" if neg else "and", [w],
                                     [f"a[{j}]", f"b[{i}]"]))
                cols[c].append(w)
        if signed and n >= t:
            w = self._new("one")                # correction one at column n
            nl.stmts.append(Stmt("const", [w], []))
            cols[n].append(w)

        # Mean value of everything that truncation discards.  In the signed
        # array the partial products of the two sign columns are inverted, so
        # their mean is 3/4 rather than 1/4, and the Baugh-Wooley correction
        # one at column n is discarded as well when T exceeds n.
        mean_trunc = 0.0
        for i in range(n):
            for j in range(n):
                c = i + j
                if c >= t:
                    continue
                neg = signed and ((i == n - 1) != (j == n - 1))
                mean_trunc += (0.75 if neg else 0.25) * (2 ** c)
        if signed and t > n:
            mean_trunc += 2.0 ** n
        scale = {0: 0.0, 1: 0.5, 2: 1.0, 3: 1.5}[comp]
        nl.const_add = int(round(mean_trunc * scale))

        # ---- 2. Dadda reduction --------------------------------------
        for s, target in enumerate(sp.targets):
            nxt: List[List[str]] = [[] for _ in range(ncol)]
            for j in range(ncol):
                bits = cols[j] + nxt[j]
                nxt[j] = []
                mode = SLOT_MODES[int(slots[s, j])]
                approx_ok = (t <= j < t + a)
                if not approx_ok:
                    mode = SLOT_MODES[0]
                if perm is not None and not mode.exact and len(bits) > 1:
                    code = int(perm[s][j]) % 3
                    if code == 1:
                        bits = bits[::-1]
                    elif code == 2:
                        bits = bits[1:] + bits[:1]
                out: List[str] = []
                while len(bits) + len(out) > target and len(bits) >= 2:
                    if (mode.c42 and len(bits) >= 4):
                        cell = CELL_BY_NAME[mode.c42]
                        ins, bits = bits[:4], bits[4:]
                    elif len(bits) >= 3:
                        cell = CELL_BY_NAME[mode.fa]
                        ins, bits = bits[:3], bits[3:]
                    else:
                        cell = CELL_BY_NAME[mode.ha]
                        ins, bits = bits[:2], bits[2:]
                    outs = []
                    for w, _ in cell.outs:
                        wire = self._new("w")
                        outs.append(wire)
                        if w == 1:
                            out.append(wire)
                        else:
                            if j + 1 < ncol:
                                nxt[j + 1].append(wire)
                    nl.stmts.append(Stmt("cell", outs, ins, cell))
                    nl.n_cells += 1
                    if not cell.exact:
                        nl.n_approx_cells += 1
                cols[j] = out + bits
            for j in range(ncol):
                cols[j] = cols[j] + nxt[j]

        # a column may still exceed 2 bits if OR-cells dropped carries; fold
        for j in range(ncol):
            while len(cols[j]) > 2:
                ins = cols[j][:3]
                cell = CELL_BY_NAME["FA"] if not (t <= j < t + a) \
                    else CELL_BY_NAME[SLOT_MODES[int(slots[-1, j])].fa]
                outs = []
                for w, _ in cell.outs:
                    wire = self._new("w")
                    outs.append(wire)
                    if w == 1:
                        cols[j].append(wire)
                    elif j + 1 < ncol:
                        cols[j + 1].append(wire)
                nl.stmts.append(Stmt("cell", outs, ins, cell))
                nl.n_cells += 1
                if not cell.exact:
                    nl.n_approx_cells += 1
                cols[j] = cols[j][3:]

        # ---- 3. final rows -------------------------------------------
        for j in range(ncol):
            if len(cols[j]) > 0:
                nl.row_a[j] = cols[j][0]
            if len(cols[j]) > 1:
                nl.row_b[j] = cols[j][1]
        # round the compensation constant to the granularity of the exact CPA
        lo = t + cpa_k
        if lo > 0 and nl.const_add:
            nl.const_add = int(round(nl.const_add / (2 ** lo))) * (2 ** lo)
        if signed:
            # the second Baugh-Wooley correction one sits at bit 2n-1, above
            # the partial-product array, so it is folded into the final adder
            nl.const_add += 1 << (2 * n - 1)
        return nl

    def _new(self, pfx: str) -> str:
        self._uid += 1
        return f"{pfx}{self._uid}"


def exact_genome(space: Space) -> np.ndarray:
    return np.zeros(space.length, dtype=np.int32)
